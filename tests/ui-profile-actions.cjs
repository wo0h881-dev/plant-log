      await fertilizer.getByRole("button", { name: "새 비료 선택", exact: true }).click();
      await fertilizer.getByRole("button", { name: "영양제 B", exact: true }).click();
      await fertilizer.getByLabel("영양제 B (mL)", { exact: true }).fill("1.5");
      await fertilizer.getByRole("button", { name: "영양제 B", exact: true }).click();
